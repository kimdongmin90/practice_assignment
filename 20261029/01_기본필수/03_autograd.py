"""실습 03: x=3에서 y=x²+2x+1과 기울기를 계산합니다."""
import torch
x = torch.tensor(3.0, requires_grad=True) # 텐서에 대한 기울기(Gradient) 계산이 필요하다 선언하는 옵션으로 변수 x 내부에 미분값(기울기)을 저장하기 위한 .grad 공간이 자동으로 개설됩니다.
                                          # torch.tensor(3.0) 명령으로 3.0 값을 가지는 0차원 스칼라 텐서를 생성합니다.
                                          # 나중에 이 변수가 포함된 수식의 끝에서 .backward()가 호출되면, 계산된 미분 수치가 .grad 방으로 오게 됩니다.
# y = x² + 2x + 1을 Tensor 연산으로 작성하세요.
# x를 Python 숫자로 바꾸지 마세요. 계산 그래프가 이어져 있어야 합니다.
# >>> B03
# TODO B03: 위 요구사항을 읽고 이 블록을 완성하세요.
y = x ** 2 + 2 * x + 1 # 요구사항인 y = x² + 2x + 1 수식으로 입력
# <<< B03
# backward는 y 값을 바꾸지 않고 x.grad에 기울기를 계산합니다.
y.backward() # 파이토치가 우리가 준 수식 y = x² + 2x + 1을 수학 미분 공식에 따라 내부적으로 미분합니다. 
print("y:", y.item()) # y.item()은 텐서 객체 안에 들어있는 단 하나의 스칼라 숫자를 파이썬의 float 데이터 타입으로 꺼내주는 함수입니다.
                      # 화면에는 y: 16.0이 출력됩니다.
print("dy/dx:", x.grad.item()) # 텐서에 담긴 수치를 파이썬의 표준 숫자 타입인 float 또는 int로 완전히 변환해 줍니다.(이 함수는 오직 단 하나의 값만 가진 0차원 스칼라 텐서에만 사용할 수 있습니다. 원소가 여러 개인 벡터나 행렬에 사용하면 에러가 발생합니다.)
                               # y.backward()가 호출되었을 때, 수학적 미분 공식과 현재 x의 위치값을 계산해 도출된 변화율(기울기) 점수가 누적 x.grad에 저장됩니다.
                               # 변환된 순수 숫자(예: 8.0)를 문자열 레이블과 결합하여 콘솔창에 dy/dx: 8.0 이라는 결과물로 최종 시각화 해줍니다.
