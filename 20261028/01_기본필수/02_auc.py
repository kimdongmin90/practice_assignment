"""실습 02: AUC에는 0/1 판정이 아니라 실패 클래스의 연속 점수를 넣습니다."""
from sklearn.metrics import roc_auc_score, roc_curve
# 정상적인 원리 예제 4건입니다. 수업용 파일의 test 결과가 아닙니다.
y = [0, 0, 1, 1]
score = [0.10, 0.40, 0.35, 0.80]
# TODO B02: roc_auc_score에 실제값과 연속 점수를 넣으세요.
auc = roc_auc_score(y, score) # 컴퓨터는 우리가 준 score를 기준으로 데이터를 높은 순서대로 줄을 세워봅니다.
                              # 
                              # 기준선(임계값)을 1등 점수 위부터 4등 점수 아래까지 이동시키며 '진짜 실패를 찾아낸 비율(TPR)'과 '정상인데 실패라고 헛다리 짚은 비율(FPR)'을 좌표 평면에 점으로 찍어 선으로 연결합니다.
                              # 인공지능이 완벽해서 실제 정답 1인 샘플들에게만 높은 점수를 주어 상위권을 1로 채웠다면 AUC는 1.0이 됩니다.
                              # 인공지능이 점수를 엉망진창 줬다면 AUC(면적)는 0.5가 됩니다.
                              # 현재 데이터로 계산된 AUC 결과값은 정확히 0.75가 나옵니다.
                              # 4개의 샘플 중 2등과 3등의 순서가 꼬여 완벽한 1.0외 되지 못하고 0.75라는 부분적인 정렬 점수를 얻게 된 것입니다.
# TODO 끝
fpr, tpr, thresholds = roc_curve(y, score)
print("FPR:", fpr.round(2).tolist())
print("TPR:", tpr.round(2).tolist())
print(f"AUC: {auc:.2f}")
print("양성 점수 0.35·0.80과 음성 점수 0.10·0.40을 네 번 비교하세요.")
